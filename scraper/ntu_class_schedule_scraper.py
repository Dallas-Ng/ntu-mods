"""
ntu_class_schedule_scraper.py
=================================

This module provides a simple scraper for the Nanyang Technological University (NTU)
class schedule portal.  The schedule pages are generated by a legacy Oracle Forms
CGI script and are not well documented.  By inspecting the underlying HTML
and form submission logic, we learned that schedules can be retrieved via a POST
request to the endpoint ``AUS_SCHEDULE.main_display1``.  The form accepts a number
of parameters:

``acadsem``
    A string in the form ``YYYY;S`` where ``YYYY`` is the academic year and
    ``S`` is one of ``1`` (Semester 1), ``2`` (Semester 2) or ``S``/``T`` (Special Term).

``r_course_yr``
    Encodes the programme/major and the study year.  For example ``CSC;;1;F``
    corresponds to *Computer Science Year 1 (Full‑time)*.  The codes are
    taken directly from the values of the programme drop‑down on the main
    page.  A few examples:

    * ``ACC;;1;F`` – Accountancy Year 1
    * ``CSC;;2;F`` – Computer Science Year 2
    * ``CSEC;;4;F`` – Computer Science and Economics Year 4

``r_subj_code``
    A free‑text field used when searching for courses by keyword or by exact
    course code.  When loading a full programme schedule this field should be
    set to ``'Enter Keywords or Course Code'``.

``r_search_type``
    Either ``'F'`` (Full‑time) or ``'P'`` (Part‑time) when performing a keyword
    search.  This field is still required for programme schedules and should
    normally be ``'F'``.

``boption``
    The action to perform.  For programme schedules use ``'CLoad'`` (Class
    Load); for keyword searches use ``'Search'``.

``staff_access``
    Always ``'false'`` for student/public access.

The :func:`scrape_programme_schedule` function builds the appropriate POST
request, fetches the resulting HTML and parses it into Python data structures.
The parsing logic is intentionally conservative: it looks for the ``* * *``
separators that the site uses to delimit courses and then extracts course
metadata and individual schedule entries line by line.  This makes the
scraper resilient to minor layout changes.

Example usage:

>>> from ntu_class_schedule_scraper import scrape_programme_schedule
>>> courses = scrape_programme_schedule(acadsem="2025;2", programme="CSC;;1;F")
>>> print(courses[0]["course_code"], courses[0]["course_title"])
CSC1010 Introduction to Programming

Please note that this script performs HTTP requests to NTU’s public schedule
server.  Some networks may require a proxy or may block such requests.  If
connecting through the container is forbidden in your environment, run the
script locally.
"""

from __future__ import annotations

import re
import html
import requests
from bs4 import BeautifulSoup
from typing import Dict, List, Optional, Tuple

__all__ = [
    "scrape_programme_schedule",
    "parse_schedule_html",
    "get_acadsem_programme_codes",
    "scrape_all_schedules",
]


def scrape_programme_schedule(
    acadsem: str,
    programme: str,
    *,
    base_url: str = "https://wish.wis.ntu.edu.sg/webexe/owa/AUS_SCHEDULE.main_display1",
    session: Optional[requests.Session] = None,
) -> List[Dict[str, object]]:
    """Retrieve and parse the class schedule for a given academic semester and programme.

    Parameters
    ----------
    acadsem: str
        Academic semester identifier in the form ``YYYY;S`` (e.g. ``'2025;2'``).

    programme: str
        Programme/Year code (value of the ``r_course_yr`` form field).  For
        example ``'CSC;;1;F'`` corresponds to Computer Science Year 1.

    base_url: str, optional
        The URL of the schedule CGI script.  It rarely changes but is exposed
        as an argument for flexibility or testing.

    session: requests.Session, optional
        Existing ``Session`` object to reuse TCP connections and cookies.

    Returns
    -------
    List[Dict[str, object]]
        A list of course dictionaries.  Each dictionary contains keys
        ``course_code``, ``course_title``, ``credits``, ``prerequisite``,
        ``remark`` and ``schedules``.  ``schedules`` is itself a list of
        dictionaries describing individual index numbers.

    Raises
    ------
    requests.HTTPError
        If the server returns an HTTP error status.

    ValueError
        If the returned page cannot be parsed according to the expected
        structure.
    """
    # Build the form data as a list of tuples instead of a dict to
    # preserve order and allow duplicate keys.  NTU's CGI expects the
    # ``acadsem`` parameter to appear twice (one for the visible select
    # element and one for the hidden field) as seen in the original
    # form submission【543245461985408†L138-L149】.  Using a list of tuples
    # preserves both occurrences.
    payload = [
        ("acadsem", acadsem),
        ("r_course_yr", programme),
        ("r_subj_code", "Enter Keywords or Course Code"),
        ("r_search_type", "F"),
        ("boption", "CLoad"),
        ("acadsem", acadsem),
        ("staff_access", "false"),
    ]

    sess = session or requests.Session()
    # Set a desktop user‑agent header to avoid trivial blocking
    headers = {
        "User-Agent": (
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
            "AppleWebKit/537.36 (KHTML, like Gecko) "
            "Chrome/118.0.0.0 Safari/537.36"
        ),
        "Origin": "https://wish.wis.ntu.edu.sg",
        "Referer": "https://wish.wis.ntu.edu.sg/webexe/owa/aus_schedule.main",
    }
    # Perform a POST request.  Although the server may accept GET, the
    # original form uses POST and is less likely to trigger caching
    # behaviour.  ``allow_redirects`` is enabled by default.
    # Inform the user which programme/semester is being scraped
    print(f"Requesting schedule for programme '{programme}' in semester '{acadsem}'...")
    response = sess.post(base_url, data=payload, headers=headers)
    response.raise_for_status()
    html_text = response.text
    courses = parse_schedule_html(html_text)
    if courses:
        print(
            f"Retrieved {len(courses)} course{'s' if len(courses) != 1 else ''} "
            f"for programme '{programme}' in semester '{acadsem}'."
        )
    else:
        print(
            f"No courses found for programme '{programme}' in semester '{acadsem}'."
        )
    return courses


def get_acadsem_programme_codes(
    *,
    main_url: str = "https://wish.wis.ntu.edu.sg/webexe/owa/aus_schedule.main",
    session: Optional[requests.Session] = None,
) -> Tuple[List[str], List[str]]:
    """Fetch the list of academic semesters and programme codes from the main schedule page.

    This helper makes a single GET request to the schedule landing page and
    parses the `<select>` elements to extract all available semester codes
    (e.g. ``'2025;2'``) and programme codes (e.g. ``'CSC;;1;F'``).  These codes
    can then be fed into :func:`scrape_programme_schedule`.

    Parameters
    ----------
    main_url: str, optional
        URL of the schedule landing page.  Defaults to the production URL.

    session: requests.Session, optional
        Existing session to reuse connections.

    Returns
    -------
    Tuple[List[str], List[str]]
        A two‑element tuple where the first element is a list of semester
        identifiers and the second element is a list of programme codes.

    Raises
    ------
    requests.HTTPError
        If the server returns a non‑OK status.
    """
    sess = session or requests.Session()
    headers = {
        "User-Agent": (
            "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
            "AppleWebKit/537.36 (KHTML, like Gecko) "
            "Chrome/118.0.0.0 Safari/537.36"
        )
    }
    print(f"Fetching list of semesters and programmes from '{main_url}'...")
    resp = sess.get(main_url, headers=headers)
    resp.raise_for_status()
    soup = BeautifulSoup(resp.text, "html.parser")
    # Extract semester codes
    sem_select = soup.find("select", attrs={"name": "acadsem"})
    if not sem_select:
        raise ValueError("Could not find 'acadsem' select element on the page")
    acadsem_values = []
    for option in sem_select.find_all("option"):
        val = option.get("value")
        if val:
            acadsem_values.append(val)
    # Extract programme codes (r_course_yr)
    prog_select = soup.find("select", attrs={"name": "r_course_yr"})
    if not prog_select:
        raise ValueError("Could not find 'r_course_yr' select element on the page")
    programme_values = []
    for option in prog_select.find_all("option"):
        val = option.get("value")
        if val:
            programme_values.append(val)
    print(
        f"Found {len(acadsem_values)} semesters and {len(programme_values)} programme codes."
    )
    return acadsem_values, programme_values


def scrape_all_schedules(
    *,
    acadsems: Optional[List[str]] = None,
    programmes: Optional[List[str]] = None,
    sleep_seconds: float = 0.5,
    session: Optional[requests.Session] = None,
) -> Dict[str, Dict[str, List[Dict[str, object]]]]:
    """Scrape schedules for all combinations of semesters and programmes.

    This function is a convenience wrapper around
    :func:`get_acadsem_programme_codes` and :func:`scrape_programme_schedule`.
    It iterates through every academic semester and every programme code,
    collecting the schedules in a nested dictionary.  The outer keys are
    ``acadsem`` strings and the inner keys are programme codes.

    Parameters
    ----------
    acadsems: list of str, optional
        If provided, only these academic semesters will be scraped.  If
        omitted, the list is fetched from the landing page.

    programmes: list of str, optional
        If provided, only these programme codes will be scraped.  If
        omitted, the list is fetched from the landing page.

    sleep_seconds: float, optional
        Number of seconds to sleep between requests.  Scraping the entire
        schedule generates a large number of requests; a small delay helps
        avoid overloading the server.  Defaults to 0.5 seconds.

    session: requests.Session, optional
        Session object to reuse connections and cookies.

    Returns
    -------
    dict
        Nested dictionary of results keyed by ``acadsem`` and then by
        programme code.  Each value is the list returned from
        :func:`scrape_programme_schedule`.

    Notes
    -----
    Scraping every programme for every semester can take a long time and
    results in hundreds of requests.  Ensure you respect the university’s
    servers by introducing delays and scraping only what you need.
    """
    sess = session or requests.Session()
    if acadsems is None or programmes is None:
        # Fetch from main page if not supplied
        all_semesters, all_programmes = get_acadsem_programme_codes(session=sess)
        if acadsems is None:
            acadsems = all_semesters
        if programmes is None:
            programmes = all_programmes
    results: Dict[str, Dict[str, List[Dict[str, object]]]] = {}
    import time
    for semester in acadsems:
        results[semester] = {}
        for prog in programmes:
            print(f"Scraping combination: semester='{semester}' programme='{prog}'")
            try:
                schedule = scrape_programme_schedule(semester, prog, session=sess)
                results[semester][prog] = schedule
            except Exception as e:
                print(
                    f"Failed to scrape programme '{prog}' in semester '{semester}': {e}"
                )
                results[semester][prog] = []
            time.sleep(sleep_seconds)
    return results


def parse_schedule_html(html_text: str) -> List[Dict[str, object]]:
    """Parse the HTML returned by ``AUS_SCHEDULE.main_display1``.

    The NTU schedule output is essentially plain text formatted with `<br>`
    elements and paragraphs.  Courses are separated by lines consisting of
    three asterisks (`* * *`).  Course details appear in a specific order:

    1. The first line contains the course code, title and credits.  For
       example: ``AAA28R CERAMICS I*~ 3.0 AU``.  Any trailing symbols like
       ``*`` or ``~`` are annotations and are stripped from the title.

    2. Zero or more ``Remark:`` or ``Prerequisite:`` lines follow.

    3. A header line ``INDEX TYPE GROUP DAY TIME VENUE REMARK`` delineates
       the start of the schedule table.

    4. One or more lines list the index number, type, group, day, time,
       venue and any remark.

    A blank line followed by another ``* * *`` separator signals the start
    of the next course.  This parser is robust against extra whitespace.

    Parameters
    ----------
    html_text: str
        Raw HTML from the schedule page.

    Returns
    -------
    List[Dict[str, object]]
        Parsed list of courses.

    Raises
    ------
    ValueError
        If the page does not appear to contain any courses.
    """
    soup = BeautifulSoup(html_text, "html.parser")
    # Extract visible text.  Use ``separator`` to insert newlines so we can
    # process the content line by line.  The schedule uses <br> tags to
    # separate fields; converting to newlines preserves that structure.
    text = soup.get_text(separator="\n")
    # Normalize whitespace: collapse multiple consecutive newlines and strip
    # leading/trailing whitespace on each line.
    lines = [ln.strip() for ln in text.split("\n")]
    # Remove empty lines
    lines = [ln for ln in lines if ln]

    # Find indices of separators ("* * *") to delineate courses
    separators = [i for i, ln in enumerate(lines) if ln.startswith("* * *")]
    # The page may begin with a separator at index 0, but if not we treat the
    # beginning of the list as the start of the first course.
    course_boundaries: List[Tuple[int, int]] = []
    if separators:
        # Add a virtual separator at the end to simplify iteration
        all_seps = separators + [len(lines)]
        for idx in range(len(separators)):
            start = separators[idx] + 1  # skip the separator itself
            end = all_seps[idx + 1]
            course_boundaries.append((start, end))
    else:
        # No separators found; assume the entire page is one course
        course_boundaries.append((0, len(lines)))

    courses: List[Dict[str, object]] = []
    # Regular expressions to parse the first line
    header_re = re.compile(r"^(?P<code>[A-Z]{2,}[0-9A-Z]+)\s+(?P<title>.*?)\s+(?P<credits>[0-9]+\.[0-9])\s+AU$",
                           re.IGNORECASE)
    # Compose patterns for schedule table rows.  Some fields may be empty.
    table_line_re = re.compile(
        r"^(?P<index>\d{4,5})\s+"  # index number (4–5 digits)
        r"(?P<type>\w+/\w+|\w+)\s+"  # e.g. LEC/STUDIO or SEM
        r"(?P<group>[^\s]+)\s+"  # group (alphanumeric)
        r"(?P<day>MON|TUE|WED|THU|FRI|SAT|SUN)\s+"
        r"(?P<time>\d{4}-\d{4})\s+"
        r"(?P<venue>[^\s]+)"  # venue (no spaces)
        r"(?:\s+(?P<remark>.*))?$"  # optional remark
    )

    for start, end in course_boundaries:
        section = lines[start:end]
        if not section:
            continue
        # Parse header line
        header_match = header_re.match(section[0])
        if not header_match:
            # Skip sections that don't match the expected pattern
            continue
        course_code = header_match.group("code").strip()
        raw_title = header_match.group("title").strip()
        # Remove trailing symbols like * ~ # from the title
        course_title = re.sub(r"[\*~#]+$", "", raw_title).strip()
        credits = float(header_match.group("credits"))
        # Initialize containers for optional info and schedules
        prerequisite: Optional[str] = None
        remark: Optional[str] = None
        schedules: List[Dict[str, str]] = []
        # Skip the first line and iterate over the rest
        iterator = iter(section[1:])
        for line in iterator:
            # Extract prerequisite and remark lines
            if line.startswith("Prerequisite:"):
                prerequisite = line.partition(":")[2].strip()
                continue
            if line.startswith("Remark:"):
                # There may be multiple remark lines; concatenate them
                current_remark = line.partition(":")[2].strip()
                if remark:
                    remark = remark + " " + current_remark
                else:
                    remark = current_remark
                continue
            # Detect table header and skip it
            if re.match(r"^INDEX\s+TYPE", line):
                continue
            # Table rows
            tbl_match = table_line_re.match(line)
            if tbl_match:
                schedules.append({
                    "index": tbl_match.group("index"),
                    "type": tbl_match.group("type"),
                    "group": tbl_match.group("group"),
                    "day": tbl_match.group("day"),
                    "time": tbl_match.group("time"),
                    "venue": tbl_match.group("venue"),
                    "remark": tbl_match.group("remark") or "",
                })
                continue
            # Ignore unrecognized lines (such as blank lines or extraneous
            # notices)
        course_dict: Dict[str, object] = {
            "course_code": course_code,
            "course_title": course_title,
            "credits": credits,
            "prerequisite": prerequisite,
            "remark": remark,
            "schedules": schedules,
        }
        courses.append(course_dict)

    # Do not raise an error if no courses were found; return an empty list instead.
    return courses


if __name__ == "__main__":
    # Simple CLI for demonstration.  This section runs only when the module
    # is executed directly, not when imported.  Users can specify the
    # academic semester and programme code via command line arguments.
    import argparse
    import json

    parser = argparse.ArgumentParser(
        description="Download and parse NTU class schedule for a given semester and programme."
    )
    parser.add_argument(
        "acadsem",
        nargs="?",
        help="Academic semester in the form 'YYYY;S', e.g. '2025;2'.  "
             "If omitted together with programme, the script scrapes all semesters.",
    )
    parser.add_argument(
        "programme",
        nargs="?",
        help="Programme/Year code (value of r_course_yr), e.g. 'CSC;;1;F'.  "
             "If omitted together with acadsem, the script scrapes all programmes.",
    )
    parser.add_argument(
        "--json", action="store_true", dest="output_json",
        help="Print the result as formatted JSON instead of Python repr",
    )
    parser.add_argument(
        "--sleep", type=float, default=0.5, dest="sleep_seconds",
        help="Seconds to sleep between requests when scraping multiple combinations."
    )
    args = parser.parse_args()
    if args.acadsem and args.programme:
        # Scrape single combination
        try:
            result = scrape_programme_schedule(args.acadsem, args.programme)
        except Exception as exc:
            parser.error(str(exc))
    else:
        # Scrape all combinations
        result = scrape_all_schedules(
            acadsems=[args.acadsem] if args.acadsem else None,
            programmes=[args.programme] if args.programme else None,
            sleep_seconds=args.sleep_seconds,
        )
    if args.output_json:
        print(json.dumps(result, indent=2, ensure_ascii=False))
    else:
        from pprint import pprint
        pprint(result)